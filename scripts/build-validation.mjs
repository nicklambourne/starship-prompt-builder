#!/usr/bin/env node
// Compile full structural validation offline; editor metadata is intentionally lossy.
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const source = new URL("../data/config-schema.json", import.meta.url);
const schema = JSON.parse(readFileSync(source, "utf8"));
// Starship v1.26.0 src/modules/env_var.rs::mixed supports bare and named
// configurations together; the upstream published map schema omits the bare form.
schema.properties.env_var.properties = Object.fromEntries(
  Object.entries(schema.$defs.EnvVarConfig.properties).map(([key, value]) =>
    [key, { anyOf: [value, { $ref: "#/$defs/EnvVarConfig" }] }]),
);
function trim(node) {
  if (!node || typeof node !== "object") return;
  // Only walk schema positions: deleting a property named "default" or "format"
  // from a properties map would remove a real Starship setting.
  delete node.description;
  delete node.default;
  delete node.title;
  if (typeof node.format === "string") {
    const limits = { uint8: [0, 255], uint32: [0, 4294967295], uint: [0, Number.MAX_SAFE_INTEGER], uint64: [0, Number.MAX_SAFE_INTEGER], int64: [Number.MIN_SAFE_INTEGER, Number.MAX_SAFE_INTEGER] };
    if (limits[node.format]) {
      // JS cannot represent arbitrary 64-bit integers losslessly.
      [node.minimum, node.maximum] = limits[node.format];
    }
    delete node.format;
  }
  for (const key of ["properties", "$defs", "patternProperties"]) {
    if (node[key]) Object.values(node[key]).forEach(trim);
  }
  for (const key of ["items", "additionalProperties", "not"]) trim(node[key]);
  for (const key of ["anyOf", "oneOf", "allOf", "prefixItems"]) node[key]?.forEach(trim);
}
trim(schema);
const ajv = new Ajv2020({ strict: false, allErrors: true, ownProperties: true, code: { source: true, esm: true }, inlineRefs: false });
const validate = ajv.compile(schema);
const output = "// Generated by scripts/build-validation.mjs; do not edit.\n" + standaloneCode(ajv, validate) + "\n";
writeFileSync(new URL("../src/lib/config/validation.generated.mjs", import.meta.url), output);
